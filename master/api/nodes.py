class MetricsSnapshotResponse(BaseModel):
    """Single metrics snapshot exposed via the stats endpoint."""
    collected_at: float
    cpu_percent: float
    cpu_load_1m: float | None = None
    cpu_load_5m: float | None = None
    cpu_load_15m: float | None = None
    cpu_cores: int | None = None
    mem_total_bytes: int
    mem_used_bytes: int
    mem_percent: float
    swap_total_bytes: int
    swap_used_bytes: int
    disk_total_bytes: int
    disk_used_bytes: int
    disk_percent: float
    uptime_seconds: float
    processes: int | None = None


class NodeStatsResponse(BaseModel):
    """Node stats endpoint response."""
    node_id: str
    snapshots: list[MetricsSnapshotResponse]


@router.get(
    "/{node_id}/stats",
    response_model=NodeStatsResponse,
    summary="Get metrics snapshots for a node (Operator+)",
)
async def get_node_stats(
    node_id: Annotated[str, Path(description="Node UUID")],
    db: DB,
    claims: Annotated[dict, Depends(require_role("operator", "admin"))],
    limit: Annotated[int, Query(ge=1, le=100, description="Number of snapshots to return")] = 10,
    nm: NodeManager = Depends(lambda: node_manager),
) -> NodeStatsResponse:
    """Return the latest metrics snapshots for a node, ordered by time descending."""
    # Verify node exists
    node = await nm.get_node(db, node_id)
    if node is None:
        raise HTTPException(status_code=status.HTTP_404_NOT_FOUND, detail="Node not found")

    rows: list[dict] = []
    async with db.execute(
        """
        SELECT
            collected_at,
            cpu_percent, cpu_load_1m, cpu_load_5m, cpu_load_15m, cpu_cores,
            mem_total_bytes, mem_used_bytes, mem_percent,
            swap_total_bytes, swap_used_bytes,
            disk_total_bytes, disk_used_bytes, disk_percent,
            uptime_seconds, processes
        FROM metrics_snapshots
        WHERE node_id = ?
        ORDER BY collected_at DESC
        LIMIT ?
        """,
        (node_id, limit),
    ) as cursor:
        for row in await cursor.fetchall():
            rows.append(dict(row))

    return NodeStatsResponse(
        node_id=node_id,
        snapshots=[MetricsSnapshotResponse(**r) for r in rows],
    )


@router.get(
    "/{node_id}/logs",
    response_model=LogsResponse,
    summary="Get live logs from a node (Operator+)",
)
async def get_node_logs(
    node_id: Annotated[str, Path(description="Node UUID")],
    db: DB,
    claims: Annotated[dict, Depends(require_role("operator", "admin"))],
    lines: Annotated[int, Query(ge=1, le=500, description="Number of log lines")] = 50,
    service: Annotated[str | None, Query(description="systemd service name (uses journalctl)")] = None,
    path: Annotated[str | None, Query(description="Log file path on the worker (/var/log/ only)")] = None,
    nm: NodeManager = Depends(lambda: node_manager),
) -> LogsResponse:
    """
    Fetch live logs from a Worker via INTENT.

    Supports two modes:
      - **Service logs** (`service` param): uses `journalctl -u <service>` on the Worker
      - **File logs** (`path` param): reads a log file from `/var/log/` on the Worker

    If neither `service` nor `path` is specified, defaults to `/var/log/syslog`.
    """
    node = await nm.get_node(db, node_id)
    if node is None:
        raise HTTPException(status_code=status.HTTP_404_NOT_FOUND, detail="Node not found")

    if service:
        action = "READ_LOGS_SERVICE"
        params = {"service": service, "lines": lines}
    elif path:
        action = "READ_LOGS"
        params = {"path": path, "lines": lines}
    else:
        action = "READ_LOGS"
        params = {"path": "/var/log/syslog", "lines": lines}

    try:
        result = await nm.send_intent(
            node_id,
            {"action": action, "params": params},
            timeout=15.0,
        )
    except RuntimeError as exc:
        raise HTTPException(
            status_code=status.HTTP_503_SERVICE_UNAVAILABLE,
            detail=str(exc),
        )
    except TimeoutError:
        raise HTTPException(
            status_code=status.HTTP_504_GATEWAY_TIMEOUT,
            detail="Worker did not respond to log request in time",
        )

    return LogsResponse(
        node_id=node_id,
        output=result.get("output", ""),
        lines=lines,
        service=service,
        path=path,
        error=result.get("error") if not result.get("success") else None,
    )


