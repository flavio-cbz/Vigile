KICKSTART_TEMPLATE = """\
#!/usr/bin/env bash
# YouCloud AI Admin — Worker Kickstart Script
# Generated by the Master Node. DO NOT EDIT.
#
# Usage:
#   curl -sSL $master_url/api/nodes/kickstart.sh | sh -s -- --token TOKEN --master MASTER_URL
#
# Requirements: curl, sha256sum (or shasum on macOS), systemd or launchd

set -euo pipefail

# ── Cleanup trap ────────────────────────────────────────────────────────────
TMPDIR_YOUCLOUD="$(mktemp -d /tmp/youcloud_install.XXXXXX)"
cleanup() {
    rm -rf "$TMPDIR_YOUCLOUD"
}
trap cleanup EXIT

# ── Argument parsing ─────────────────────────────────────────────────────────
JOIN_TOKEN=""
MASTER_URL=""

while [[ $# -gt 0 ]]; do
    case "$1" in
        --token)   JOIN_TOKEN="$2"; shift 2 ;;
        --master)  MASTER_URL="$2"; shift 2 ;;
        *)         echo "Unknown argument: $1"; exit 1 ;;
    esac
done

if [[ -z "$JOIN_TOKEN" || -z "$MASTER_URL" ]]; then
    echo "ERROR: --token and --master are required." >&2
    exit 1
fi

# ── OS / Arch detection ──────────────────────────────────────────────────────
OS="$(uname -s | tr '[:upper:]' '[:lower:]')"
ARCH="$(uname -m)"

case "$ARCH" in
    x86_64)         ARCH="amd64" ;;
    aarch64|arm64)  ARCH="arm64" ;;
    armv7l)         ARCH="armv7" ;;
    *)
        echo "ERROR: Unsupported architecture: $ARCH" >&2
        exit 1
        ;;
esac

case "$OS" in
    linux|darwin|freebsd) ;;
    *)
        echo "ERROR: Unsupported OS: $OS" >&2
        exit 1
        ;;
esac

echo "[youcloud] Detected: $OS/$ARCH"

# ── Binary download ───────────────────────────────────────────────────────────
BINARY_URL="$MASTER_URL/api/nodes/binary/$OS/$ARCH/worker"
HASH_URL="$BINARY_URL.sha256"
BINARY_PATH="$TMPDIR_YOUCLOUD/worker"

echo "[youcloud] Downloading Worker binary..."
curl -sSfL "$BINARY_URL" -o "$BINARY_PATH"

echo "[youcloud] Verifying SHA256..."
EXPECTED_HASH="$(curl -sSfL "$HASH_URL")"
if command -v sha256sum &>/dev/null; then
    ACTUAL_HASH="$(sha256sum "$BINARY_PATH" | awk '{print $1}')"
else
    ACTUAL_HASH="$(shasum -a 256 "$BINARY_PATH" | awk '{print $1}')"
fi

if [[ "$EXPECTED_HASH" != "$ACTUAL_HASH" ]]; then
    echo "ERROR: SHA256 mismatch! Binary may be corrupted or tampered." >&2
    echo "  Expected: $EXPECTED_HASH" >&2
    echo "  Got:      $ACTUAL_HASH" >&2
    exit 1
fi

echo "[youcloud] SHA256 OK."
chmod +x "$BINARY_PATH"

# ── Installation ──────────────────────────────────────────────────────────────
INSTALL_DIR="/usr/local/bin"
CONFIG_DIR="/etc/youcloud"

echo "[youcloud] Installing Worker to $INSTALL_DIR/youcloud-worker..."
install -m 0755 "$BINARY_PATH" "$INSTALL_DIR/youcloud-worker"

mkdir -p "$CONFIG_DIR"
chmod 700 "$CONFIG_DIR"

echo "[youcloud] Storing enrollment token..."
printf '%s' "$JOIN_TOKEN" > "$CONFIG_DIR/enrollment.token"
chmod 600 "$CONFIG_DIR/enrollment.token"

printf '%s' "$MASTER_URL" > "$CONFIG_DIR/master_url"
chmod 600 "$CONFIG_DIR/master_url"

# ── Systemd service installation ──────────────────────────────────────────────
if command -v systemctl &>/dev/null; then
    cat > /etc/systemd/system/youcloud-worker.service <<EOF
[Unit]
Description=YouCloud AI Admin — Worker Node
After=network-online.target
Wants=network-online.target

[Service]
Type=simple
ExecStart=/usr/local/bin/youcloud-worker
Restart=always
RestartSec=5
StandardOutput=journal
StandardError=journal
SyslogIdentifier=youcloud-worker
NoNewPrivileges=true
ProtectSystem=strict
ReadWritePaths=/etc/youcloud
PrivateTmp=true

[Install]
WantedBy=multi-user.target
EOF

    systemctl daemon-reload
    systemctl enable --now youcloud-worker
    echo "[youcloud] systemd service enabled and started."

elif command -v launchctl &>/dev/null; then
    # macOS launchd (Sprint 2 — placeholder for now)
    echo "[youcloud] macOS detected. launchd support coming in Sprint 2."
else
    echo "[youcloud] WARNING: No init system detected. Start manually:"
    echo "  youcloud-worker"
fi

echo "[youcloud] Installation complete! The Worker will enroll automatically."
echo "[youcloud] Check status: systemctl status youcloud-worker
"""


