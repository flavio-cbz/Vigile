@router.post(
    "/generate-join",
    response_model=JoinTokenResponse,
    summary="Generate an enrollment token and kickstart command (Admin only)",
    status_code=status.HTTP_201_CREATED,
)
async def generate_join_token(
    body: GenerateJoinRequest,
    request: Request,
    db: DB,
    claims: Annotated[dict, Depends(require_role("admin"))],
    sec: SecurityManager = Depends(get_security),
    nm: NodeManager = Depends(lambda: node_manager),
) -> JoinTokenResponse:
    """
    Generate a JOIN_TOKEN for a new Worker Node.

    Steps:
      1. Pre-create the node entry in PENDING state
      2. Generate HMAC-SHA256 signed JOIN_TOKEN
      3. Store token hash in DB (never store raw token)
      4. Return the curl command for the kickstart script

    The token is single-use and expires in 30 minutes.
    """
    from master.config import settings

    # 1. Pre-create node
    node_id = await nm.create_node(db, name=body.name, ip_prefix=body.ip_prefix)

    # 2. Generate JOIN_TOKEN (returns token + payload together)
    token, payload = sec.generate_join_token(node_id=node_id, ip_prefix=body.ip_prefix)
    token_hash = sec.join_token_hash(token)

    # 3. Store token in DB
    token_id = str(uuid.uuid4())
    now = time.time()
    await db.execute(
        """
        INSERT INTO join_tokens (id, node_id, token_hash, payload_b64, consumed, expires_at, created_at)
        VALUES (?, ?, ?, ?, 0, ?, ?)
        """,
        (
            token_id,
            node_id,
            token_hash,
            token.split(".", 1)[1],
            payload["expires_at"],
            now,
        ),
    )
    await db.commit()

    # 4. Audit
    await log_action(
        db,
        user_id=claims["sub"],
        action="GENERATE_JOIN_TOKEN",
        node_id=node_id,
        details={"node_name": body.name, "ip_prefix": body.ip_prefix},
    )

    master_url = settings.master_url
    curl_command = (
        f"curl -sSL {master_url}/api/nodes/kickstart.sh | "
        f"sh -s -- --token {token} --master {master_url}"
    )

    expires_in = int(payload["expires_at"] - now)
    logger.info(
        "JOIN_TOKEN generated: node_id=%s name=%s expires_in=%ds",
        node_id, body.name, expires_in,
    )

    return JoinTokenResponse(
        node_id=node_id,
        token=token,
        expires_in=expires_in,
        curl_command=curl_command,
    )


@router.get(
    "/kickstart.sh",
    response_class=PlainTextResponse,
    summary="Download the Worker installation script",
)
async def get_kickstart_script(request: Request) -> PlainTextResponse:
    """
    Return the kickstart shell script.

    This endpoint is public (no auth required) so the curl | sh pipeline works
    without pre-authentication. Security comes from the JOIN_TOKEN validation
    in Phase 2 of the enrollment process.
    """
    from master.config import settings

    # Sanitize: escape $ to prevent bash variable expansion in the generated script
    safe_url = settings.master_url.replace("$", "\\$")
    script = KICKSTART_TEMPLATE.replace("$master_url", safe_url)
    return PlainTextResponse(
        content=script,
        media_type="text/x-sh",
        headers={"Content-Disposition": "inline; filename=kickstart.sh"},
    )


@router.get(
    "",
    response_model=list[NodeResponse],
    summary="List all nodes (Operator+)",
)
async def list_nodes(
    db: DB,
    claims: Annotated[dict, Depends(require_role("operator", "admin"))],
    state: str | None = Query(default=None, description="Filter by state"),
    nm: NodeManager = Depends(lambda: node_manager),
) -> list[NodeResponse]:
    """Return a list of all registered nodes, optionally filtered by state."""
    nodes = await nm.list_nodes(db, state=state)
    return [NodeResponse(**_node_to_response(n)) for n in nodes]


@router.get(
    "/{node_id}",
    response_model=NodeResponse,
    summary="Get a node's details (Operator+)",
)
async def get_node(
    node_id: Annotated[str, Path(description="Node UUID")],
    db: DB,
    claims: Annotated[dict, Depends(require_role("operator", "admin"))],
    nm: NodeManager = Depends(lambda: node_manager),
) -> NodeResponse:
    """Fetch detailed information for a single node."""
    node = await nm.get_node(db, node_id)
    if node is None:
        raise HTTPException(status_code=status.HTTP_404_NOT_FOUND, detail="Node not found")
    return NodeResponse(**_node_to_response(node))


@router.delete(
    "/{node_id}",
    status_code=status.HTTP_204_NO_CONTENT,
    summary="Revoke a node (Admin only)",
)
async def revoke_node(
    node_id: Annotated[str, Path(description="Node UUID")],
    db: DB,
    claims: Annotated[dict, Depends(require_role("admin"))],
    nm: NodeManager = Depends(lambda: node_manager),
) -> None:
    """
    Revoke a node: disconnect it, invalidate its tokens, and mark it REVOKED.
    This action is permanent — a new enrollment is required to re-add the node.
    """
    node = await nm.get_node(db, node_id)
    if node is None:
        raise HTTPException(status_code=status.HTTP_404_NOT_FOUND, detail="Node not found")

    if node["state"] == NodeState.REVOKED.value:
        raise HTTPException(
            status_code=status.HTTP_409_CONFLICT,
            detail="Node is already revoked",
        )

    await nm.revoke_node(db, node_id, revoked_by=claims["sub"])

    await log_action(
        db,
        user_id=claims["sub"],
        action="REVOKE_NODE",
        node_id=node_id,
        details={"node_name": node.get("name"), "previous_state": node["state"]},
    )

    logger.warning("Node %s revoked by user %s", node_id, claims["sub"])


